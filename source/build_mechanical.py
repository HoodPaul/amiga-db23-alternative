#!/usr/bin/env python3
"""Rebuild the DB23 mechanical fit prototype from the shared JSON parameters.

OpenSCAD is the canonical STL route. CadQuery exports matching analytic STEP
geometry for the holder; these are fit-prototype parts, not measured connectors.
"""
from pathlib import Path
import json, math, subprocess, re, struct, collections

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'mechanical'
P = json.loads((ROOT / 'source/design_parameters.json').read_text())
H, M, B = P['holder'], P['motherboard'], P['pcb']
OUT.mkdir(exist_ok=True)

# These are local mechanical design choices, not dimensions attributed to the
# original connector. Change and rerun, or edit the generated SCAD for trials.
S = dict(rail_inner_x=17.25, rail_top_z=2.00,
         tower_inner_x=18.60, tower_rear_y=4.80, tower_top_z=11.00,
         anchor_boss_top_z=2.40,
         rear_ledge_front_y=14.00,
         pcb_lateral_clearance=0.25,
         shield_access_width=4.40, shield_access_front_y=11.80,
         shield_access_rear_y=14.80,
         keeper_height=1.20, keeper_tongue_length=1.20,
         keeper_fit_clearance=0.15)
PINS = [(i*M['pin_pitch']-5.5*M['pin_pitch'], M['rear_row_y']) for i in range(12)]
PINS += [(i*M['pin_pitch']-5*M['pin_pitch'], M['front_row_y']) for i in range(11)]

V = dict(overall_width=H['overall_width'], front_y=H['front_y'], rear_y=H['rear_y'],
         bottom_z=H['bottom_clearance'], pin_block_width=H['pin_block_width'],
         pin_block_front_y=H['pin_block_front_y'], pin_block_rear_y=H['pin_block_rear_y'],
         pin_block_top_z=H['pin_block_top_z'], guide_d=H['pin_guide_hole_diameter'],
         anchor_x=M['anchor_spacing']/2, anchor_y=M['anchor_y'],
         anchor_d=H['anchor_clearance_diameter'],
         jackpost_d=H['jackpost_through_diameter'],
         nut_af=H['nut_across_flats_assumed'], nut_t=H['nut_thickness_assumed'],
         nut_clearance=H['nut_pocket_clearance'],
         nut_y=H['nut_axis_y_assumed'], nut_z=H['nut_axis_z'],
         pcb_bottom_z=B['bottom_z'], pcb_half_width=B['width']/2,
         shield_x=B['shield_pad_x'], **S)

SCAD_HEADER = '''// DB23 replacement v0.3: UNMEASURED CONNECTOR FIT PROTOTYPE
// Generated by source/build_mechanical.py from source/design_parameters.json.
// mm; x across port, y inward from flange, z above motherboard top.
// Genuine solder-cup connector must be measured before declaring a fit.
// Cable-facing thread: 4-40 UNC. Captive nut matches ACTUAL rear stem.
// Guide diameter 0.92 is nominal geometry: printer compensation is separate.
// For 0.64 square pins, theoretical minimum circle is 0.9051 mm before clearance.
// Main holder bottom is z=0.6. Fit the two supplied 0.6 mm anchor shims below it.
// Export examples: openscad -o holder.stl -D 'part="holder"' this_file.scad
// Choose holder, coupon, nut_keeper, anchor_shims, anchor_shim, or assembly.
part="holder";
$fn=64;
'''
SCAD = SCAD_HEADER + ''.join(f'{k}={json.dumps(v)};\n' for k,v in V.items())
SCAD += 'pin_grid='+json.dumps(PINS)+';\n'
SCAD += r'''
eps=0.03;
nut_pocket_af=nut_af+nut_clearance;
nut_pocket_t=nut_t+nut_clearance;
nut_R=nut_pocket_af/sqrt(3);
nut_y0=nut_y-nut_pocket_t/2;
nut_y1=nut_y+nut_pocket_t/2;
function hexpts(af)=[for(a=[30:60:330]) [af/sqrt(3)*cos(a),af/sqrt(3)*sin(a)]];
module box(x0,x1,y0,y1,z0,z1) {
 translate([x0,y0,z0]) cube([x1-x0,y1-y0,z1-z0]);
}
module zhole(x,y,d,z0,z1){translate([x,y,z0]) cylinder(d=d,h=z1-z0);}
module yhole(x,z,d,y0,y1){
 translate([x,y0,z]) rotate([-90,0,0]) cylinder(d=d,h=y1-y0);
}
module nut_slot(x){
 // Hex points project to X/Z; inspect wall thickness after changing nut sizes.
 translate([x,nut_y1,nut_z]) rotate([90,0,0])
   linear_extrude(height=nut_pocket_t) polygon(hexpts(nut_pocket_af));
 // Top-loading continuation of the pocket. Screw stem retains the nut once fitted.
 box(x-nut_pocket_af/2,x+nut_pocket_af/2,nut_y0,nut_y1,
     nut_z,tower_top_z+eps);
}
module holder(){difference(){union(){
 // Common planar bottom: place this part flat on the printer bed.
 box(-pin_block_width/2,pin_block_width/2,pin_block_front_y,
     pin_block_rear_y,bottom_z,pin_block_top_z);
 for(s=[-1,1]){
   if(s==1){
     box(rail_inner_x,overall_width/2,front_y,rear_y,bottom_z,rail_top_z);
     box(tower_inner_x,overall_width/2,front_y,tower_rear_y,bottom_z,tower_top_z);
   }else{
     box(-overall_width/2,-rail_inner_x,front_y,rear_y,bottom_z,rail_top_z);
     box(-overall_width/2,-tower_inner_x,front_y,tower_rear_y,bottom_z,tower_top_z);
   }
   translate([s*anchor_x,anchor_y,bottom_z])
     cylinder(d=overall_width-2*anchor_x,h=anchor_boss_top_z-bottom_z);
 }
 // Rear edge ledge supports the PCB behind all 23 tail pads.
 box(-pcb_half_width,pcb_half_width,rear_ledge_front_y,rear_y,
     bottom_z,pcb_bottom_z);
 // Low lateral stops guide the PCB. Open top permits assembly/removal.
 box(pcb_half_width+pcb_lateral_clearance,pcb_half_width+pcb_lateral_clearance+0.8,
     12.5,rear_y,bottom_z,pcb_bottom_z+0.65);
 box(-pcb_half_width-pcb_lateral_clearance-0.8,-pcb_half_width-pcb_lateral_clearance,
     12.5,rear_y,bottom_z,pcb_bottom_z+0.65);
 }
 // Every pin guide is an uninterrupted through bore through the full pin block.
 for(p=pin_grid) zhole(p[0],p[1],guide_d,bottom_z-eps,pin_block_top_z+eps);
 for(s=[-1,1]){
   zhole(s*anchor_x,anchor_y,anchor_d,bottom_z-eps,tower_top_z+eps);
   yhole(s*anchor_x,nut_z,jackpost_d,front_y-eps,tower_rear_y+eps);
   nut_slot(s*anchor_x);
   // Open underside access to J3 shield-wire solder pads, not trapped blind holes.
   box(s*shield_x-shield_access_width/2,s*shield_x+shield_access_width/2,
       shield_access_front_y,shield_access_rear_y,bottom_z-eps,pcb_bottom_z+1);
 }
}}
module nut_keeper(){
 // Print two. Loose keeper is optional; fitted jackpost stem already traps its nut.
 w=overall_width/2-tower_inner_x;
 union(){
   box(-w/2,w/2,front_y,tower_rear_y,0,keeper_height);
   box(-nut_pocket_af/2+keeper_fit_clearance/2,
        nut_pocket_af/2-keeper_fit_clearance/2,
        nut_y0+keeper_fit_clearance/2,nut_y1-keeper_fit_clearance/2,
        -keeper_tongue_length,eps);
 }
}
module anchor_shims(){
 for(s=[-1,1]) difference(){
   translate([s*5,0,0]) cylinder(d=7,h=bottom_z);
   zhole(s*5,0,anchor_d,-eps,bottom_z+eps);
 }
}
module coupon(){
 // Actual 23-hole staggered grid plus eight independent hole-size trials.
 difference(){
   box(-21,21,0,22,0,3);
   for(i=[0:7]) zhole(-16.8+i*4.8,5,0.75+i*0.05,-eps,3+eps);
   for(p=pin_grid) zhole(p[0],p[1]+5.4,guide_d,-eps,3+eps);
 }
 for(i=[0:7]) translate([-16.8+i*4.8,1.7,2.99])
   linear_extrude(0.36) text(str(0.75+i*0.05),size=1.3,
     halign="center",valign="center",font="DejaVu Sans:style=Bold");
 translate([0,20,2.99]) linear_extrude(0.36)
   text(str("23-PIN GRID  ",guide_d),size=1.65,
     halign="center",valign="center",font="DejaVu Sans:style=Bold");
}
if(part=="holder") holder();
if(part=="coupon") coupon();
// Keeper exports with its broad flat cap on the bed and the tongue upwards.
if(part=="nut_keeper") translate([0,0,keeper_height]) rotate([0,180,0]) nut_keeper();
if(part=="anchor_shims") anchor_shims();
if(part=="anchor_shim") difference(){cylinder(d=7,h=bottom_z);zhole(0,0,anchor_d,-eps,bottom_z+eps);}
if(part=="assembly"){
 color("grey") holder();
 for(s=[-1,1]) color("orange")
   translate([s*anchor_x,0,tower_top_z]) nut_keeper();
 for(s=[-1,1]) color("orange") translate([s*anchor_x,anchor_y,0])
   difference(){cylinder(d=7,h=bottom_z);zhole(0,0,anchor_d,-eps,bottom_z+eps);}
}
'''
scad_path=OUT/'DB23_Holder_v0.3.scad'
scad_path.write_text(SCAD)

def mesh_stats(path):
    """Read STL, validate manifold edges and report connected components/volume."""
    data=path.read_bytes()
    count=struct.unpack('<I',data[80:84])[0] if len(data)>=84 else 0
    tris=[]
    if len(data)==84+50*count:
        for i in range(count):
            vals=struct.unpack('<12fH',data[84+i*50:134+i*50])
            tris.append([tuple(round(q,5) for q in vals[j:j+3]) for j in (3,6,9)])
    else:
        vs=[tuple(round(float(q),5) for q in v) for v in re.findall(rb'vertex\s+([\-+.0-9eE]+)\s+([\-+.0-9eE]+)\s+([\-+.0-9eE]+)',data)]
        tris=[vs[i:i+3] for i in range(0,len(vs),3)]
    edges=collections.Counter()
    graph=collections.defaultdict(set)
    volume=0
    for tri in tris:
        a,b,c=tri
        volume+=(a[0]*(b[1]*c[2]-b[2]*c[1])+a[1]*(b[2]*c[0]-b[0]*c[2])+a[2]*(b[0]*c[1]-b[1]*c[0]))/6
        for v,w in ((a,b),(b,c),(c,a)):
            edges[tuple(sorted((v,w)))]+=1; graph[v].add(w);graph[w].add(v)
    unseen=set(graph); components=0
    while unseen:
        components+=1; todo=[unseen.pop()]
        while todo:
            for w in graph[todo.pop()]:
                if w in unseen: unseen.remove(w);todo.append(w)
    bad=sum(n!=2 for n in edges.values())
    pts=list(graph)
    return dict(triangles=len(tris),nonmanifold_edges=bad,components=components,
                volume_mm3=round(volume,3),
                bounds=[[min(p[i] for p in pts),max(p[i] for p in pts)] for i in range(3)])

results={}
for part,stem in [('holder','DB23_Holder_v0.3'),('coupon','DB23_Hole_Fit_Coupon_v0.3'),
                  ('nut_keeper','DB23_Nut_Keeper_v0.3'),('anchor_shims','DB23_Anchor_Shims_v0.3'),
                  ('anchor_shim','DB23_Anchor_Shim_Single_v0.3')]:
    target=OUT/(stem+'.stl')
    run=subprocess.run(['openscad','--export-format','binstl','-o',str(target),'-D',f'part="{part}"',str(scad_path)],
                       capture_output=True,text=True,check=True)
    stats=mesh_stats(target)
    if stats['nonmanifold_edges'] or (part!='anchor_shims' and stats['components']!=1) or stats['volume_mm3']<=0:
        raise RuntimeError(f'Invalid mesh: {target.name}: {stats}')
    results[target.name]=stats

# Matching analytic B-rep STEP. Coupon text remains an STL-only print feature.
try:
    import cadquery as cq
    def box(x0,x1,y0,y1,z0,z1):
        return cq.Solid.makeBox(x1-x0,y1-y0,z1-z0,cq.Vector(x0,y0,z0))
    def zc(x,y,d,z0,z1):
        return cq.Solid.makeCylinder(d/2,z1-z0,cq.Vector(x,y,z0))
    def yc(x,z,d,y0,y1):
        return cq.Solid.makeCylinder(d/2,y1-y0,cq.Vector(x,y0,z),cq.Vector(0,1,0))
    v=V; bx=H['pin_block_width']/2; bz=H['bottom_clearance']; hw=H['overall_width']/2
    solids=[box(-bx,bx,H['pin_block_front_y'],H['pin_block_rear_y'],bz,H['pin_block_top_z'])]
    for side in (-1,1):
        x0,x1=sorted([side*S['rail_inner_x'],side*hw])
        solids.append(box(x0,x1,H['front_y'],H['rear_y'],bz,S['rail_top_z']))
        x0,x1=sorted([side*S['tower_inner_x'],side*hw])
        solids.append(box(x0,x1,H['front_y'],S['tower_rear_y'],bz,S['tower_top_z']))
        solids.append(zc(side*v['anchor_x'],v['anchor_y'],H['overall_width']-2*v['anchor_x'],bz,S['anchor_boss_top_z']))
    solids.append(box(-B['width']/2,B['width']/2,S['rear_ledge_front_y'],H['rear_y'],bz,B['bottom_z']))
    lc=S['pcb_lateral_clearance']
    solids.append(box(B['width']/2+lc,B['width']/2+lc+.8,12.5,H['rear_y'],bz,B['bottom_z']+.65))
    solids.append(box(-B['width']/2-lc-.8,-B['width']/2-lc,12.5,H['rear_y'],bz,B['bottom_z']+.65))
    shape=solids[0].fuse(*solids[1:])
    cutters=[zc(x,y,H['pin_guide_hole_diameter'],bz-.1,H['pin_block_top_z']+.1) for x,y in PINS]
    af=H['nut_across_flats_assumed']+H['nut_pocket_clearance']
    t=H['nut_thickness_assumed']+H['nut_pocket_clearance']
    ny0,ny1=H['nut_axis_y_assumed']-t/2,H['nut_axis_y_assumed']+t/2
    for side in (-1,1):
        ax=side*v['anchor_x']; az=H['nut_axis_z']
        cutters.extend([zc(ax,v['anchor_y'],H['anchor_clearance_diameter'],bz-.1,S['tower_top_z']+.1),
                        yc(ax,az,H['jackpost_through_diameter'],H['front_y']-.1,S['tower_rear_y']+.1)])
        poly=[cq.Vector(ax+af/math.sqrt(3)*math.cos(math.radians(a)),ny0,
                        az+af/math.sqrt(3)*math.sin(math.radians(a))) for a in range(30,331,60)]
        wire=cq.Wire.makePolygon(poly+[poly[0]])
        cutters.append(cq.Solid.extrudeLinear(wire,[],cq.Vector(0,t,0)))
        cutters.append(box(ax-af/2,ax+af/2,ny0,ny1,az,S['tower_top_z']+.1))
        sx=side*B['shield_pad_x'];sw=S['shield_access_width']/2
        cutters.append(box(sx-sw,sx+sw,S['shield_access_front_y'],S['shield_access_rear_y'],bz-.1,B['bottom_z']+1))
    shape=shape.cut(*cutters).clean()
    if not shape.isValid() or len(shape.Solids())!=1:
        raise RuntimeError('STEP holder is invalid or disconnected')
    cq.exporters.export(shape,str(OUT/'DB23_Holder_v0.3.step'))
    # Verify that all 23 bores actually traverse the solid, rather than relying
    # only on an externally closed STL mesh or a picture of the top face.
    blocked=[]
    for i,(x,y) in enumerate(PINS):
        if shape.intersect(zc(x,y,H['pin_guide_hole_diameter']-.002,bz-.01,H['pin_block_top_z']+.01)).Volume()>1e-5:
            blocked.append(i+1)
    if blocked:
        raise RuntimeError(f'Blocked pin guide bores: {blocked}')
    results['DB23_Holder_v0.3.step']=dict(valid=True,solids=len(shape.Solids()),volume_mm3=round(shape.Volume(),3),
                                         pin_bores_checked=23,blocked_pin_bores=blocked)
except ImportError:
    results['STEP']=dict(exported=False,reason='CadQuery not installed; STL build complete')

(OUT/'mechanical_validation.json').write_text(json.dumps(results,indent=2)+'\n')
print(json.dumps(results,indent=2))
